    "import pandas as pd\n",
    "import sqlite3\n",
    "import logging\n",
    "import os\n",
    "import time\n",
    "\n",
    "# Logging Setup\n",
    "os.makedirs(\"Logs\", exist_ok=True)\n",
    "\n",
    "logging.basicConfig(\n",
    "    filename=\"Logs/get_vendor_summary.log\",\n",
    "    level=logging.DEBUG,\n",
    "    format=\"%(asctime)s - %(levelname)s - %(message)s\",\n",
    "    filemode=\"a\"\n",
    ")\n",
    "\n",
    "# Cleaning Function\n",
    "def clean_data(df):\n",
    "\n",
    "    logging.info(\"Cleaning data started\")\n",
    "\n",
    "    # Fill missing values\n",
    "    df.fillna(0, inplace=True)\n",
    "\n",
    "    # Remove extra spaces\n",
    "    df[\"VendorName\"] = df[\"VendorName\"].str.strip()\n",
    "    df[\"Description\"] = df[\"Description\"].str.strip()\n",
    "\n",
    "    # Calculate Gross Profit\n",
    "    df[\"GrossProfit\"] = (\n",
    "        df[\"TotalSalesDollars\"] - df[\"total_pur_dollars\"]\n",
    "    )\n",
    "\n",
    "    # Calculate Profit Margin\n",
    "    df[\"ProfitMargin\"] = (\n",
    "        df[\"GrossProfit\"] / df[\"TotalSalesDollars\"]\n",
    "    ) * 100\n",
    "\n",
    "    # Calculate Stock Turnover\n",
    "    df[\"StockTurnover\"] = (\n",
    "        df[\"TotalSalesQuantity\"] / df[\"total_pur_qty\"]\n",
    "    )\n",
    "\n",
    "    # Calculate Sales to Purchase Ratio\n",
    "    df[\"SalesToPurchaseRatio\"] = (\n",
    "        df[\"TotalSalesDollars\"] / df[\"total_pur_dollars\"]\n",
    "    )\n",
    "\n",
    "    # Handle infinite values\n",
    "    df.replace([float(\"inf\"), -float(\"inf\")], 0, inplace=True)\n",
    "\n",
    "    logging.info(\"Cleaning data completed\")\n",
    "\n",
    "    return df\n",
    "\n",
    "\n",
